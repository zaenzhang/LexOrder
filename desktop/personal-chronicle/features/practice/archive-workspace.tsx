"use client"

import { WorkspaceLoading } from "@/kit/ui-patterns/workspace-loading"
import Link from "@/features/shell/workspace-link"
import { useState } from "react"
import { useQuery } from "@tanstack/react-query"
import { Button } from "@/components/ui/button"
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card"
import { Input } from "@/components/ui/input"
import { Textarea } from "@/components/ui/textarea"
import { NativeSelect, NativeSelectOption } from "@/components/ui/native-select"
import { Sheet, SheetContent, SheetHeader, SheetTitle } from "@/components/ui/sheet"
import { PageHeader } from "@/kit/ui-patterns/page-header"
import { CaseForm } from "@/features/matters/case-management"
import { readPersonal } from "@/features/matters/personal-client"

const api = "/api/personal/archive"
const url = (matter: string, extra: Record<string, string> = {}) =>
  api + "?" + new URLSearchParams({ matter, ...extra })
const post = (data: object) =>
  readPersonal(api, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(data),
  })
const archiveStatus: Record<string, string> = {
  PENDING_REVIEW: "待逐项核验",
  APPROVED: "已批准",
  REJECTED: "已退回",
}
const categories = {
  CONTRACT: "合同",
  EVIDENCE: "证据",
  PLEADING: "诉讼文书",
  PROCEDURE: "程序文书",
  JUDGMENT: "裁判文书",
  OTHER: "其他材料",
}
const decisions: Record<string, string> = {
  ATTACHED: "已附材料",
  MISSING: "缺失",
  NOT_APPLICABLE: "不适用",
  AUTO_GENERATED: "自动生成",
}
type Doc = { id: string; name: string }
type Item = { id: string } & { label: string; required: boolean; autoGenerated?: boolean }
type Policy = {
  configured: boolean
  name: string
  version: string
  effectiveAt: string
  sourceFileId: string | null
  sourceFileName: string | null
}
type RecordBrief = { id: string; archiveNo: string; status: string; summary: string }
type Prep = {
  checklist: { title: string; items: Item[] }
  docsByItem: Record<string, Doc[]>
  documents: Doc[]
  archiveFolder: Doc | null
  summary: string | null
  manualChecks: { id: string; label: string }[]
  closedReasons: Record<string, string>
}
type Procedure = { id: string; name: string; updatedAt: string }
type Board = {
  procedures: Procedure[]
  canSchedule: boolean
  matter: { id: string; title: string; internalCode: string; status: string; statusLabel: string }
  canLifecycle: boolean
  canSubmit: boolean
  blockers: string[]
  currentPlan: boolean
  archives: RecordBrief[]
  policy: Policy
  policyFiles: Doc[]
  prep: Prep | null
}
type Review = {
  legacy: boolean
  policy: Policy | null
  items: { id: string; label: string; status: string; required: boolean; note: string; documentIds: string[] }[]
  manualChecks: { id: string; label: string; note: string }[]
  documents: (Doc & { version: number; sha256: string; size: number })[]
  excludedDocuments: Doc[]
  verificationIds: string[]
  hasExceptions: boolean
}
type Detail = {
  review: Review | null
  fields: { label: string; value: string }[]
  status: string
  canReview: boolean
}
const policySource = (id: string) => "/api/firm-files/" + id + "/download"

export function ArchiveWorkspace({ matterId }: { matterId: string }) {
  const board = useQuery({
    queryKey: ["archive", matterId],
    queryFn: ({ signal }) => readPersonal<Board>(url(matterId), { signal }),
    retry: false,
  })
  const [dialog, setDialog] = useState<"submit" | "policy" | "reopen" | "close">()
  const [procedure, setProcedure] = useState<Procedure>()
  const [record, setRecord] = useState<RecordBrief>()
  const [notice, setNotice] = useState("")
  const state = board.data
  const flow = "/practice/operations?section=closure&matter=" + encodeURIComponent(matterId)
  function done() {
    setProcedure(undefined)
    setRecord(undefined)
    setDialog(undefined)
    setNotice("已保存。")
    void board.refetch()
  }
  return (
    <section className="grid min-w-0 gap-4">
      <PageHeader
        title="正式归档"
        description={state?.matter.title}
        actions={
          <Link className="text-sm underline" href={flow}>
            返回归档检查
          </Link>
        }
      />
      {board.isPending && <WorkspaceLoading label="正在读取归档资料…" />}
      {board.error && (
        <p role="alert">
          {board.error.message}{" "}
          <Button size="sm" variant="outline" onClick={() => void board.refetch()}>
            重试
          </Button>
        </p>
      )}
      {notice && <p role="status">{notice}</p>}
      {state && (
        <>
          <Card>
            <CardHeader>
              <CardTitle>
                {state.matter.internalCode} · {state.matter.statusLabel}
              </CardTitle>
            </CardHeader>
            <CardContent className="grid gap-3 text-sm">
              {state.canSchedule &&
                state.procedures.map((p) => (
                  <div key={p.id} className="flex items-center gap-2">
                    {p.name}
                    <Button size="sm" variant="outline" onClick={() => setProcedure(p)}>
                      登记实际程序终结
                    </Button>
                  </div>
                ))}
              {state.blockers.map((v) => (
                <p key={v}>{v}</p>
              ))}
              {!state.currentPlan && (
                <Link className="underline" href={flow}>
                  核对并保存本案收尾安排
                </Link>
              )}
              {state.policy.configured ? (
                <p>
                  制度 · {state.policy.name} · {state.policy.version} · {state.policy.effectiveAt}{" "}
                  <a className="underline" href={policySource(state.policy.sourceFileId!)} download>
                    下载制度原文
                  </a>
                </p>
              ) : (
                <p>尚未配置本工作区的归档制度。</p>
              )}
              <div className="flex flex-wrap gap-2">
                <Button size="sm" variant="outline" onClick={() => setDialog("policy")}>
                  设置归档制度
                </Button>
                {state.canSubmit && (
                  <Button
                    size="sm"
                    disabled={
                      !!state.blockers.length ||
                      !state.currentPlan ||
                      !state.policy.configured ||
                      state.archives.some((r) => r.status === "PENDING_REVIEW")
                    }
                    onClick={() => setDialog("submit")}
                  >
                    {state.matter.status === "ARCHIVED" ? "提交补充归档" : "准备归档申请"}
                  </Button>
                )}
                {state.canLifecycle && ["CLOSED", "ON_HOLD"].includes(state.matter.status) && (
                  <Button size="sm" variant="outline" onClick={() => setDialog("reopen")}>
                    重新开放案件
                  </Button>
                )}
                {state.canLifecycle && !["ARCHIVED", "CLOSED"].includes(state.matter.status) && (
                  <Button size="sm" variant="outline" onClick={() => setDialog("close")}>
                    办理结案
                  </Button>
                )}
              </div>
            </CardContent>
          </Card>
          <Card>
            <CardHeader>
              <CardTitle>归档记录</CardTitle>
            </CardHeader>
            <CardContent className="grid gap-3 text-sm">
              {!state.archives.length && <p>尚无正式归档申请。</p>}
              {state.archives.map((r) => (
                <div key={r.id} className="grid gap-1 border-b pb-2">
                  <strong>
                    {r.archiveNo} · {archiveStatus[r.status] ?? r.status}
                  </strong>
                  <p>{r.summary}</p>
                  <div className="flex flex-wrap gap-3">
                    <Button size="sm" variant="outline" onClick={() => setRecord(r)}>
                      查看送审快照
                    </Button>
                    {r.status === "APPROVED" && (
                      <a
                        className="self-center underline"
                        href={url(matterId, { archiveId: r.id, download: "1" })}
                        download
                      >
                        导出本版归档 ZIP
                      </a>
                    )}
                  </div>
                </div>
              ))}
            </CardContent>
          </Card>
          {procedure && (
            <CaseForm
              title="保存实际程序终结"
              close={() => setProcedure(undefined)}
              saved={done}
              onSave={(f) =>
                post({
                  action: "finish-procedure",
                  matterId,
                  procedureId: procedure.id,
                  expectedUpdatedAt: procedure.updatedAt,
                  concludedAt: f.get("day") + "T00:00:00+08:00",
                  outcome: f.get("outcome"),
                  outcomeNote: f.get("note"),
                })
              }
            >
              <h3>{procedure.name}</h3>
              <label>
                实际终结日期
                <Input name="day" type="date" required />
              </label>
              <label>
                结果
                <NativeSelect name="outcome" defaultValue="" required>
                  <NativeSelectOption value="">请选择</NativeSelectOption>
                  {Object.entries({
                    WON: "胜诉",
                    PARTIAL_WON: "部分胜诉",
                    LOST: "败诉",
                    MEDIATED: "调解",
                    WITHDRAWN: "撤回",
                    DISMISSED: "驳回",
                    COMPLETED: "完成",
                    TRANSFERRED: "移交",
                    OTHER: "其他",
                  }).map(([k, v]) => (
                    <NativeSelectOption key={k} value={k}>
                      {v}
                    </NativeSelectOption>
                  ))}
                </NativeSelect>
              </label>
              <label>
                结果说明
                <Textarea name="note" required maxLength={500} />
              </label>
            </CaseForm>
          )}
          {dialog === "policy" && (
            <CaseForm
              title="保存归档制度"
              close={() => setDialog(undefined)}
              saved={done}
              onSave={(f) => post({ action: "policy", matterId, ...Object.fromEntries(f) })}
            >
              <p>本设置适用于整个个人工作区。批准记录保留当时采用的制度版本。</p>
              <Link href="/practice/resources" className="underline">
                在工作资源导入制度原文
              </Link>
              <label>
                制度名称
                <Input name="name" required defaultValue={state.policy.configured ? state.policy.name : ""} />
              </label>
              <label>
                版本
                <Input
                  name="version"
                  required
                  defaultValue={state.policy.configured ? state.policy.version : ""}
                />
              </label>
              <label>
                生效日期
                <Input name="effectiveAt" type="date" required defaultValue={state.policy.effectiveAt} />
              </label>
              <label>
                制度原文
                <NativeSelect name="sourceFileId" required defaultValue={state.policy.sourceFileId ?? ""}>
                  <NativeSelectOption value="">选择工作区制度文件</NativeSelectOption>
                  {state.policyFiles.map((f) => (
                    <NativeSelectOption key={f.id} value={f.id}>
                      {f.name}
                    </NativeSelectOption>
                  ))}
                </NativeSelect>
              </label>
            </CaseForm>
          )}
          {(dialog === "close" || dialog === "reopen") && (
            <CaseForm
              title={dialog === "close" ? "确认结案" : "确认重新开放"}
              close={() => setDialog(undefined)}
              saved={done}
              onSave={(f) => post({ action: dialog, matterId, ...Object.fromEntries(f) })}
            >
              <p>
                {state.matter.title} · {state.matter.statusLabel}
              </p>
              {dialog === "close" ? (
                <label>
                  结案小结
                  <Textarea name="summary" required maxLength={2000} />
                </label>
              ) : (
                <p>将恢复到办理中，并在本案时间线登记本次重新开放。</p>
              )}
            </CaseForm>
          )}
          {dialog === "submit" && state.prep && (
            <SubmitArchive matterId={matterId} prep={state.prep} close={() => setDialog(undefined)} done={done} />
          )}
          {record && (
            <ReviewArchive matterId={matterId} record={record} close={() => setRecord(undefined)} done={done} />
          )}
        </>
      )}
    </section>
  )
}

function SubmitArchive({
  matterId,
  prep,
  close,
  done,
}: {
  matterId: string
  prep: Prep
  close: () => void
  done: () => void
}) {
  const [list, setList] = useState(prep.documents)
  const [selected, setSelected] = useState<Record<string, string[]>>(() =>
    Object.fromEntries(Object.entries(prep.docsByItem).map(([k, v]) => [k, v.map((d) => d.id)]))
  )
  const [states, setStates] = useState<Record<string, string>>(() =>
    Object.fromEntries(
      prep.checklist.items.map((i) => [i.id, prep.docsByItem[i.id]?.length ? "ATTACHED" : "MISSING"])
    )
  )
  const [error, setError] = useState("")
  const [busy, setBusy] = useState(false)
  const [uploadKeys] = useState(() => new Map<File, string>())
  const items = prep.checklist.items.filter((i) => !i.autoGenerated)
  async function attach(i: Item, file: File, category: string) {
    setBusy(true)
    setError("")
    const f = new FormData()
    const key = uploadKeys.get(file) ?? crypto.randomUUID()
    uploadKeys.set(file, key)
    f.set("matterId", matterId)
    f.set("itemId", i.id)
    f.set("file", file)
    f.set("category", category)
    f.set("requestKey", key)
    try {
      const doc = await readPersonal<Doc>(api, { method: "POST", body: f })
      setList((v) => (v.some((d) => d.id === doc.id) ? v : [...v, doc]))
      setSelected((v) => ({ ...v, [i.id]: [...new Set([...(v[i.id] ?? []), doc.id])] }))
      setStates((v) => ({ ...v, [i.id]: "ATTACHED" }))
    } catch (e) {
      setError(e instanceof Error ? e.message : "入卷失败。")
    } finally {
      setBusy(false)
    }
  }
  return (
    <CaseForm
      title="提交归档申请"
      close={() => {
        if (!busy) close()
      }}
      saved={done}
      onSave={(f) => {
        if (busy) throw new Error("请等待当前文件完成入卷。")
        const checklistItems = Object.fromEntries(
          items.map((i) => [
            i.id,
            {
              status: states[i.id],
              documentIds: states[i.id] === "ATTACHED" ? (selected[i.id] ?? []) : [],
              note: f.get("note-" + i.id) ?? "",
            },
          ])
        )
        const manualChecks = Object.fromEntries(
          prep.manualChecks.map((i) => [i.id, { confirmed: f.has("manual-" + i.id), note: "" }])
        )
        return post({
          action: "submit",
          data: {
            matterId,
            summary: f.get("summary"),
            closedReason: f.get("reason"),
            completedAt: f.get("date") + "T00:00:00+08:00",
            judgmentSummary: f.get("judgment"),
            checklistItems,
            manualChecks,
            forceWithMissing: f.has("exceptions"),
          },
        })
      }}
    >
      <h3 className="font-medium">{prep.checklist.title}</h3>
      <label>
        结案方式
        <NativeSelect required name="reason" defaultValue="">
          <NativeSelectOption value="">请选择</NativeSelectOption>
          {Object.entries(prep.closedReasons).map(([v, k]) => (
            <NativeSelectOption key={v} value={v}>
              {k}
            </NativeSelectOption>
          ))}
        </NativeSelect>
      </label>
      <label>
        实际完成日期
        <Input type="date" name="date" required />
      </label>
      <label>
        结案小结
        <Textarea name="summary" required maxLength={4000} defaultValue={prep.summary ?? ""} />
      </label>
      <label>
        裁判结果摘要
        <Textarea name="judgment" maxLength={2000} />
      </label>
      {items.map((i) => (
        <fieldset className="grid gap-2 border p-2" key={i.id}>
          <legend>
            {i.label}
            {i.required ? "（必交）" : ""}
          </legend>
          <NativeSelect
            aria-label={i.label + "状态"}
            value={states[i.id]}
            onChange={(e) => setStates((v) => ({ ...v, [i.id]: e.target.value }))}
          >
            {["ATTACHED", "MISSING", "NOT_APPLICABLE"].map((v) => (
              <NativeSelectOption value={v} key={v}>
                {decisions[v]}
              </NativeSelectOption>
            ))}
          </NativeSelect>
          {states[i.id] === "ATTACHED" && (
            <label>
              关联的卷内版本
              <select
                className="block w-full border bg-background"
                multiple
                required
                value={selected[i.id] ?? []}
                onChange={(e) => {
                  const ids = Array.from(e.target.selectedOptions, (v) => v.value)
                  setSelected((v) => ({ ...v, [i.id]: ids }))
                }}
              >
                {list.map((d) => (
                  <option key={d.id} value={d.id}>
                    {d.name}
                  </option>
                ))}
              </select>
            </label>
          )}
          <label>
            说明
            <Input
              name={"note-" + i.id}
              maxLength={1000}
              required={states[i.id] === "NOT_APPLICABLE" || (i.required && states[i.id] !== "ATTACHED")}
            />
          </label>
          <details>
            <summary>从本地补传本项材料</summary>
            <div className="grid gap-2 py-2">
              <NativeSelect name={"cat-" + i.id} aria-label="补传材料类别" defaultValue="OTHER">
                {Object.entries(categories).map(([k, v]) => (
                  <NativeSelectOption key={k} value={k}>
                    {v}
                  </NativeSelectOption>
                ))}
              </NativeSelect>
              <Input type="file" name={"file-" + i.id} aria-label={i.label + "补传文件"} />
              <Button
                type="button"
                size="sm"
                variant="outline"
                disabled={busy}
                onClick={(e) => {
                  const f = new FormData(e.currentTarget.form!)
                  const file = f.get("file-" + i.id)
                  if (file instanceof File && file.size) void attach(i, file, String(f.get("cat-" + i.id)))
                  else setError("请选择要补传的文件。")
                }}
              >
                入卷并选用
              </Button>
            </div>
          </details>
        </fieldset>
      ))}
      {busy && <p role="status">正在入卷…</p>}
      {error && <p role="alert">{error}</p>}
      {prep.manualChecks.map((i) => (
        <label key={i.id} className="flex gap-2">
          <input type="checkbox" name={"manual-" + i.id} required />
          {i.label}
        </label>
      ))}
      {items.some((i) => i.required && states[i.id] !== "ATTACHED") && (
        <label className="flex gap-2">
          <input type="checkbox" required name="exceptions" />
          已逐项说明缺项，申请例外核准
        </label>
      )}
    </CaseForm>
  )
}

function ReviewArchive({
  matterId,
  record,
  close,
  done,
}: {
  matterId: string
  record: RecordBrief
  close: () => void
  done: () => void
}) {
  const result = useQuery({
    queryKey: ["archive-review", matterId, record.id],
    queryFn: ({ signal }) => readPersonal<Detail>(url(matterId, { archiveId: record.id }), { signal }),
    retry: false,
  })
  const [form, setForm] = useState<"approve" | "reject">()
  const data = result.data
  const review = data?.review
  const check = (id: string) =>
    form === "approve" && review?.verificationIds.includes(id) ? (
      <input type="checkbox" name="verified" value={id} required aria-label={"已核对 " + id} />
    ) : null
  function sheetContents() {
    return (
      <>
        {data?.fields.map((f) => (
          <p key={f.label}>
            {f.label} · {f.value}
          </p>
        ))}
        {review?.legacy && <p>历史申请未保存材料快照，可退回后重新提交。</p>}
        {review?.policy && (
          <a className="underline" href={policySource(review.policy.sourceFileId!)} download>
            制度原文 · {review.policy.name} · {review.policy.version}
          </a>
        )}
        {review?.items.map((i) => (
          <label key={i.id} className="flex gap-2">
            {check("item:" + i.id)}
            <span>
              {i.label} · {decisions[i.status]}
              {i.note ? " · " + i.note : ""}
              {i.documentIds.map((id) => (
                <small key={id} className="block">
                  {review.documents.find((d) => d.id === id)?.name}
                </small>
              ))}
            </span>
          </label>
        ))}
        {review?.manualChecks.map((i) => (
          <label className="flex gap-2" key={i.id}>
            {check("manual:" + i.id)}
            <span>
              {i.label}
              {i.note ? " · " + i.note : ""}
            </span>
          </label>
        ))}
        {review?.documents.map((d) => (
          <div key={d.id} className="flex gap-2">
            {check("document:" + d.id)}
            <div>
              <a className="underline" href={"/api/documents/" + d.id + "/download"} download>
                {d.name} · V{d.version}
              </a>
              <small className="block break-all">SHA-256 · {d.sha256}</small>
            </div>
          </div>
        ))}
        {!!review?.excludedDocuments.length && (
          <details>
            <summary>未列入本次快照的材料（{review.excludedDocuments.length}）</summary>
            {review.excludedDocuments.map((d) => (
              <p key={d.id}>{d.name}</p>
            ))}
          </details>
        )}
      </>
    )
  }
  if (form && review)
    return (
      <CaseForm
        title={form === "approve" ? "核验通过并归档" : "退回归档申请"}
        close={() => setForm(undefined)}
        saved={done}
        onSave={(f) =>
          form === "approve"
            ? post({
                action: "approve",
                matterId,
                data: {
                  archiveId: record.id,
                  note: f.get("note"),
                  exceptionApproved: f.has("exception"),
                  verificationIds: f.getAll("verified"),
                },
              })
            : post({ action: "reject", matterId, archiveId: record.id, note: f.get("note") })
        }
      >
        <h3>{record.archiveNo}</h3>
        {sheetContents()}
        {form === "approve" && review.hasExceptions && (
          <label>
            <input name="exception" type="checkbox" required /> 已核准所列缺项及不适用理由
          </label>
        )}
        <label>
          {form === "reject" ? "退回原因" : "核验意见"}
          <Textarea name="note" maxLength={500} required={form === "reject" || review.hasExceptions} />
        </label>
      </CaseForm>
    )
  return (
    <Sheet
      open
      onOpenChange={(v) => {
        if (!v) close()
      }}
    >
      <SheetContent className="overflow-y-auto">
        <SheetHeader>
          <SheetTitle>送审快照 · {record.archiveNo}</SheetTitle>
        </SheetHeader>
        <div className="grid gap-3 px-4 pb-4 text-sm">
          {result.isPending && <p role="status">正在读取快照…</p>}
          {result.error && (
            <p role="alert">
              {result.error.message}
              <Button variant="outline" size="sm" onClick={() => void result.refetch()}>
                重试
              </Button>
            </p>
          )}
          {sheetContents()}
          {data?.canReview && (
            <div className="flex gap-2">
              {review && !review.legacy && <Button onClick={() => setForm("approve")}>开始逐项核验</Button>}
              <Button variant="outline" onClick={() => setForm("reject")}>
                退回
              </Button>
            </div>
          )}
        </div>
      </SheetContent>
    </Sheet>
  )
}

import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { fixture } from "./fixture.mjs";

const {cases:[a,b],request}=await fixture();
const ep="/api/personal/matter-workspace";
const post=async (body,status)=>(await request(ep,body,status)).json();
const view=async m=>(await request(ep+"?matter="+m.id+"&section=materials")).json();
const name="卷内验收-"+randomUUID().slice(0,8);
const file=new FormData();
file.set("file",new File([name],name+".txt",{type:"text/plain"}));
for(const [k,v] of Object.entries({name,category:"EVIDENCE",matterId:a.id,requestKey:randomUUID()}))file.set(k,v);
await post(file);
const doc=(await view(a)).documents.find(d=>d.name===name);
assert(doc);
const folder=await post({action:"create-volume",matterId:a.id,name});
const filing={action:"file-in-volume",documentId:doc.id,folderId:folder.id,matterId:a.id};
await post({...filing,matterId:b.id},403);
await post(filing);
await post({action:"rename-volume",matterId:b.id,folderId:folder.id,name:name+"甲"},403);
await post({action:"rename-volume",matterId:a.id,folderId:folder.id,name:name+"甲"});
const current=await view(a);
assert.equal(current.documents.find(d=>d.id===doc.id).folderId,folder.id);
assert.equal(current.folders.find(f=>f.id===folder.id).name,name+"甲");
assert.equal((await view(b)).folders.some(f=>f.id===folder.id),false);
assert.equal(await(await request("/api/documents/"+doc.id+"/download")).text(),name);
await post({...filing,folderId:null});
assert.equal((await view(a)).documents.find(d=>d.id===doc.id).folderId,null);
console.log("PASS case-specific volume creation, filing, rename, unfiling, immutable bytes and cross-case guards");

import { z } from "zod";
import { ActionError } from "@/lib/action-error";
import { requireSession } from "@/lib/auth/session";
import { canApproveItem } from "@/lib/approvals/service";
import { ARCHIVE_MANUAL_CHECKS } from "@/lib/archive/snapshot";
import { matterStatusLabel, procedureTypeLabel } from "@/lib/enums";
import { matterAssociationFilter } from "@/lib/permissions";
import { prisma } from "@/lib/prisma";
import { hasCustomPermission } from "@/lib/roles/catalog";
import { isPersonalMode } from "@/lib/runtime/mode";
import { personalChannelAllowed } from "@/lib/runtime/personal-channel";
import { getApprovalDetail } from "@/server/approval-permissions/inbox";
import { approveArchiveRecord, archiveMatter, getArchivePrepData, rejectArchiveRecord } from "@/server/archive/actions";
import { getClosureBoard } from "@/server/archive/closure-actions";
import { getArchivePolicySettings, saveArchivePolicy } from "@/server/archive/policy";
import { archiveApproveSchema, archiveSubmitSchema, CLOSED_REASON_CN } from "@/server/archive/schemas";
import { uploadDocument } from "@/server/documents/actions";
import { updateProcedure } from "@/server/procedures/actions";
import { procedureOutcomeSchema } from "@/server/procedures/schemas";
import { closeMatter, reopenMatter } from "@/server/matters/lifecycle";
import { GET as exportArchive } from "@/app/api/archive/[matterId]/export/route";

const id = z.cuid();
const actions = z.discriminatedUnion("action", [
  z.object({ action: z.literal("submit"), data: archiveSubmitSchema }),
  z.object({ action: z.literal("approve"), matterId: id, data: archiveApproveSchema }),
  z.object({ action: z.literal("reject"), matterId: id, archiveId: id, note: z.string().trim().min(1).max(500) }),
  z.object({ action: z.literal("finish-procedure"), matterId: id, procedureId: id, expectedUpdatedAt: z.coerce.date(), concludedAt: z.coerce.date(), outcome: procedureOutcomeSchema, outcomeNote: z.string().trim().min(1).max(500) }),
  z.object({ action: z.literal("close"), matterId: id, summary: z.string().trim().min(1).max(2000) }),
  z.object({ action: z.literal("reopen"), matterId: id }),
  z.object({ action: z.literal("policy"), matterId: id, name: z.string(), version: z.string(), effectiveAt: z.string(), sourceFileId: id }),
]);
const headers = { "Cache-Control": "no-store" };
const json = (value: unknown, status = 200) => Response.json(value, { status, headers });

async function handle(req: Request) {
  if (!isPersonalMode()) return new Response(null, { status: 404, headers });
  if (!personalChannelAllowed(req.headers, { method: req.method })) return new Response(null, { status: 403, headers });
  try {
    const session = await requireSession("archive.read");
    const query = new URL(req.url).searchParams;
    const form = req.method === "POST" && req.headers.get("content-type")?.startsWith("multipart/form-data;") ? await req.formData() : null;
    const action = req.method === "POST" && !form ? actions.parse(await req.json().catch(() => null)) : null;
    const matterId = action ? (action.action === "submit" ? action.data.matterId : action.matterId) : id.parse(form?.get("matterId") ?? query.get("matter"));
    const matter = await prisma.matter.findFirst({
      where: { id: matterId, deletedAt: null, ...matterAssociationFilter(session.user.id) },
      select: { id: true, title: true, internalCode: true, status: true, ownerId: true,
        members: { where: { userId: session.user.id, role: { in: ["LEAD", "CO_LEAD"] } }, select: { userId: true } } },
    });
    if (!matter) return json({ error: "案件不存在或无权办理。" }, 404);
    if (form) {
      const prep = await getArchivePrepData(matterId);
      const itemId = z.string().parse(form.get("itemId"));
      const item = prep.checklist.items.find(i => i.id === itemId && !i.autoGenerated);
      const file = form.get("file");
      if (!item || !(file instanceof File)) return json({ error: "请选择清单项和相应文件。" }, 400);
      if (matter.status === "ARCHIVED" && !prep.archiveFolder) return json({error:"本案缺少归档卷宗。"},409);
      const payload = new FormData();
      payload.set("matterId",matterId); payload.set("file",file); payload.set("name",file.name); payload.set("archiveChecklistItemId",item.id);
      payload.set("category",z.enum(["CONTRACT","EVIDENCE","PLEADING","PROCEDURE","JUDGMENT","OTHER"]).parse(form.get("category")));
      payload.set("requestKey",z.uuid().parse(form.get("requestKey")));
      if (prep.archiveFolder) payload.set("folderId",prep.archiveFolder.id);
      const saved = await uploadDocument(payload);
      return saved.ok ? json({id:saved.id,name:file.name}) : json({error:saved.message},409);
    }
    const archiveId = action?.action === "approve" ? action.data.archiveId : action?.action === "reject" ? action.archiveId
      : query.has("archiveId") ? id.parse(query.get("archiveId")) : null;
    if (archiveId && !await prisma.archiveRecord.count({ where: { id: archiveId, matterId } }))
      return json({ error: "归档记录不存在或不属于本案。" }, 404);
    if (action) {
      if (action.action === "finish-procedure") {
        if (!await prisma.matterProcedure.count({where:{matterId,id:action.procedureId,status:{not:"CONCLUDED"}}}))return json({error:"本案没有该待终结程序。"},409);
        return json(await updateProcedure({id:action.procedureId,expectedUpdatedAt:action.expectedUpdatedAt,concludedAt:action.concludedAt,
          status:"CONCLUDED",outcome:action.outcome,outcomeNote:action.outcomeNote}));
      }
      if (action.action === "submit") return json(await archiveMatter(action.data));
      if (action.action === "approve") return json(await approveArchiveRecord(action.data));
      if (action.action === "reject") return json(await rejectArchiveRecord({ archiveId: action.archiveId, note: action.note }));
      if (action.action === "close") return json(await closeMatter({ id: matterId, summary: action.summary }));
      if (action.action === "reopen") return json(await reopenMatter(matterId));
      return json(await saveArchivePolicy({ name: action.name, version: action.version, effectiveAt: action.effectiveAt, sourceFileId: action.sourceFileId }));
    }
    if (query.get("download") === "1") {
      if (!archiveId) return json({ error: "请选择已批准的归档编号。" }, 400);
      return exportArchive(req, { params: Promise.resolve({ matterId }) });
    }
    if (archiveId) {
      const detail = await getApprovalDetail({ action: "ARCHIVE_APPROVE", id: archiveId });
      const canReview = detail.status === "PENDING" && await canApproveItem(session.user.id, "ARCHIVE_APPROVE", archiveId);
      return json({ fields: detail.fields, review: detail.archiveReview, status: detail.status, canReview });
    }
    const board = await getClosureBoard(matterId);
    if (!board) return json({ error: "案件收尾数据不可读取。" }, 404);
    const leader = matter.ownerId === session.user.id || matter.members.length > 0;
    const canPrepare = leader && board.canSave;
    const [prep, settings] = await Promise.all([canPrepare ? getArchivePrepData(matterId) : null, getArchivePolicySettings()]);
    const openProcedures=await prisma.matterProcedure.findMany({where:{matterId, engagement:"ENGAGED",status:{not:"CONCLUDED"}},
      select:{id:true,updatedAt:true,customLabel:true,type:true,caseNumber:true},orderBy:{order:"asc"}});
    return json({ procedures:openProcedures.map(p=>({id:p.id,updatedAt:p.updatedAt,name:[p.customLabel||procedureTypeLabel[p.type],p.caseNumber].filter(Boolean).join(" · ")})),
      canSchedule:matter.status!=="ARCHIVED"&&hasCustomPermission(session.user,"schedule.write"),matter: { id: matter.id, title: matter.title, internalCode: matter.internalCode, status: matter.status, statusLabel: matterStatusLabel[matter.status] },
      canLifecycle: leader && hasCustomPermission(session.user,"matters.write"), canSubmit: canPrepare && (matter.status !== "ARCHIVED" || board.canSupplement),
      blockers: board.blockers, currentPlan: !!board.plan && (board.plan.current || matter.status === "ARCHIVED"), archives:board.archives,
      policy: settings.policy, policyFiles: settings.files.map(({id,name,sha256})=>({id,name,sha256})),
      prep: prep && { checklist: prep.checklist, docsByItem: prep.docsByItem, documents: prep.availableDocuments, summary: prep.existingSummary, archiveFolder: prep.archiveFolder,
        manualChecks: ARCHIVE_MANUAL_CHECKS, closedReasons: CLOSED_REASON_CN } });
  } catch (error) {
    if (error instanceof z.ZodError) return json({ error: error.issues[0]?.message ?? "归档资料无效。" }, 400);
    if (error instanceof ActionError) return json({ error: error.message }, 409);
    throw error;
  }
}
export { handle as GET, handle as POST };

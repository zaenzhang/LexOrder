import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";

const { prep, upload, submit, refresh } = vi.hoisted(() => ({ prep: vi.fn(), upload: vi.fn(), submit: vi.fn(), refresh: vi.fn() }));
vi.mock("@/server/archive/actions", () => ({ getArchivePrepData: prep, archiveMatter: submit }));
vi.mock("@/server/documents/actions", () => ({ uploadDocument: upload }));
vi.mock("next/navigation", () => ({ useRouter: () => ({ refresh }) }));
vi.mock("sonner", () => ({ toast: { success: vi.fn() } }));

import { ArchiveWizardDialog } from "@/app/(app)/matters/[id]/_components/archive-wizard";

const MATTER = "cmatter000000000000000001";
const FOLDER = "cfolder000000000000000001";
const DOC = "cdocument000000000000001";
function data(uploaded = false) {
  return {
    matter: { id: MATTER, status: "ARCHIVED", closedAt: new Date("2026-01-01T00:00:00Z") },
    checklist: { kind: "LITIGATION", title: "合成材料清单", items: [{ id: "contract", label: "委托合同", required: false, autoGenerated: false }] },
    policy: { configured: true, name: "合成制度", version: "1", effectiveAt: "2026-01-01", sourceFileId: "cpolicy000000000000000001", sourceFileName: "合成制度.txt" },
    archiveFolder: { id: FOLDER, name: "归档" }, existingSummary: "原结案小结",
    docsByItem: uploaded ? { contract: [{ id: DOC, name: "补充合同" }] } : {},
    availableDocuments: uploaded ? [{ id: DOC, name: "补充合同", category: "CONTRACT", mimeType: "text/plain", size: 4, folderName: "归档" }] : [],
  };
}
async function selectFile() {
  fireEvent.click(await screen.findByRole("button", { name: "补传材料" }));
  fireEvent.change(screen.getByLabelText("补传归档材料"), { target: { files: [new File(["test"], "补充合同.txt", { type: "text/plain" })] } });
}

beforeEach(() => {
  vi.resetAllMocks();
  vi.stubGlobal("ResizeObserver", class { observe() {} unobserve() {} disconnect() {} });
  prep.mockResolvedValue(data());
  upload.mockResolvedValue({ ok: true, id: DOC });
});
afterEach(() => { cleanup(); vi.unstubAllGlobals(); });

describe("补充归档材料入口", () => {
  it("上传传入本案合法归档 folderId，刷新材料不覆盖小结草稿", async () => {
    prep.mockResolvedValueOnce(data()).mockResolvedValue(data(true));
    render(<ArchiveWizardDialog matterId={MATTER} open onOpenChange={vi.fn()} />);
    fireEvent.change(await screen.findByLabelText("结案小结 *"), { target: { value: "正在填写的补充小结" } });
    await selectFile();
    await waitFor(() => expect(upload).toHaveBeenCalledOnce());
    const form = upload.mock.calls[0][0] as FormData;
    expect(form.get("matterId")).toBe(MATTER);
    expect(form.get("folderId")).toBe(FOLDER);
    expect(form.get("archiveChecklistItemId")).toBe("contract");
    await screen.findByText("已关联 1 份");
    expect(screen.getByLabelText("结案小结 *")).toHaveValue("正在填写的补充小结");
  });

  it("加载失败留在当前操作，提供真实重试入口", async () => {
    const onOpenChange = vi.fn();
    prep.mockRejectedValueOnce(new Error("暂时无法读取归档资料")).mockResolvedValue(data());
    render(<ArchiveWizardDialog matterId={MATTER} open onOpenChange={onOpenChange} />);
    await screen.findByText("暂时无法读取归档资料");
    expect(onOpenChange).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole("button", { name: "重试加载" }));
    await screen.findByLabelText("结案小结 *");
    expect(prep).toHaveBeenCalledTimes(2);
  });

  it("上传成功但列表刷新失败只重试刷新，不重复上传", async () => {
    prep.mockResolvedValueOnce(data()).mockRejectedValueOnce(new Error("列表暂时不可读取")).mockResolvedValue(data(true));
    render(<ArchiveWizardDialog matterId={MATTER} open onOpenChange={vi.fn()} />);
    await selectFile();
    await screen.findByText("材料已保存，列表刷新失败：列表暂时不可读取");
    fireEvent.click(screen.getByRole("button", { name: "刷新材料" }));
    await waitFor(() => expect(screen.queryByText("材料已保存，列表刷新失败：列表暂时不可读取")).not.toBeInTheDocument());
    expect(upload).toHaveBeenCalledOnce();
    await screen.findByText("已关联 1 份");
  });

  it("归档案件缺少合法卷宗时明确阻止补传，不改普通上传规则", async () => {
    prep.mockResolvedValue({ ...data(), archiveFolder: null });
    render(<ArchiveWizardDialog matterId={MATTER} open onOpenChange={vi.fn()} />);
    expect(await screen.findByRole("button", { name: "补传材料" })).toBeDisabled();
    expect(screen.getByText("本案没有可用的结案或归档卷宗，请先核对卷宗设置后补传材料。")).toBeInTheDocument();
    expect(upload).not.toHaveBeenCalled();
  });
});
